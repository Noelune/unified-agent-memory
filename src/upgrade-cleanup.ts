/**
 * upgrade-cleanup — the declarative half of the update scheme.
 *
 * `planUpgrade`/`runUpgrade` reconcile what this build OWNS: add what is
 * missing, rewrite what drifted. Nothing there ever deletes, which is right
 * for user-owned files and wrong for everything a *previous* version left
 * behind: deploy.py writes one `.bak-<stamp>` per actual change and nothing
 * prunes them; a crash between temp write and rename leaves a `.tmp-deploy` /
 * `.tmp-upgrade` stub; the pre-0.8 fixed-name index DB stays forever; and the
 * next release that renames an artifact would otherwise need bespoke
 * migration code.
 *
 * So removal lives here as DATA. Every file this build ever deletes is one
 * entry in `RETIRED_PATHS` (exact paths a former version wrote that this
 * build no longer owns) or `GARBAGE_RULES` (filename shapes this project
 * generates, with a retention bound). A future release that retires or
 * renames a file appends one row — no new migration script, no per-release
 * update plan — and the reconcile pass applies it idempotently on every
 * subsequent boot.
 *
 * Two rules bind every entry:
 *
 *  1. **Only shapes this project creates.** A retired path is named exactly;
 *     a garbage rule matches a filename we generate (deploy.py's
 *     `.bak-<stamp>` and `.tmp-deploy`, upgrade-run's `.tmp-upgrade`,
 *     common.atomic_write's dotfile `.<name>.<8hex>.tmp`). A user file can
 *     only be hit by coinciding with that exact generated shape.
 *  2. **Never canonical vault content.** The vault-side rule scans dotfiles
 *     only — our temps start with a dot; user notes, sync-conflict copies and
 *     the forget area's real files never do — and nothing else in the vault
 *     is ever scanned for deletion.
 *
 * The sweep is best-effort hygiene and must never gate an upgrade: per-file
 * failures are collected and reported, not raised.
 *
 * @module src/upgrade-cleanup
 */

import { readdirSync, statSync, unlinkSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** Everything the sweep needs from the outside world; all paths injectable. */
export interface CleanupDeps {
  home: string
  /** The vault, or null when unconfigured (vault-side rules then skip). */
  vaultPath: string | null
  /** Existing agent instruction files; their dirs are where deploy.py backs up. */
  instructionFiles: readonly string[]
  now?: () => Date
}

/** One file the sweep wants gone, and why. */
export interface CleanupTarget {
  path: string
  /** Which declaration asked for it; shown in reports. */
  rule: string
  sizeBytes: number
}

/** What a completed sweep did. */
export interface CleanupResult {
  removed: Array<{ path: string; rule: string }>
  /** Files that matched but could not be removed (locked, permissions). */
  failed: Array<{ path: string; rule: string }>
  freedBytes: number
}

/** A path a previous version may have written and this build no longer owns. */
export interface RetiredArtifact {
  /** Stable id for reports. */
  key: string
  /** What it was and why it is gone; shown to the user. */
  reason: string
  /** Absolute candidate paths. Missing ones are skipped silently. */
  paths: (deps: CleanupDeps) => string[]
}

/**
 * Retirements declared so far.
 *
 * To retire (or rename) an artifact in a future release, append one entry —
 * that is the whole migration:
 *
 *   {
 *     key: 'old-shim-name',
 *     reason: '0.9 renamed the wrapper; the old one is never invoked',
 *     paths: (d) => [join(d.home, '.unified-memory', 'bin', 'memory.old')],
 *   }
 *
 * Empty today: every file the current build writes is one it still owns.
 */
export const RETIRED_PATHS: RetiredArtifact[] = []

/** A filename shape this project generates, with an optional retention bound. */
export interface GarbageRule {
  key: string
  /** Directories to scan, one level deep — siblings of the files we write. */
  dirs: (deps: CleanupDeps) => string[]
  /** Full-name shape generated by this project; anything else is never touched. */
  match: RegExp
  /** Remove all but the N newest matches (the newest backup is the rollback target). */
  keepNewest?: number
  /** Only remove matches not modified within this window; undefined = any age. */
  olderThanMs?: number
  /** Only remove when a sibling in the same dir matches this (a successor exists). */
  requiresSibling?: RegExp
}

/** deploy.py backup stamps: `AGENTS.md.bak-20261024-120000-000[-01]`. */
const BACKUP_SUFFIX = /\.bak-\d{8}-\d{6}-\d{3}(?:-\d{2})?$/
/** Crash leftovers of the two atomic writers; a concurrent writer may own one, so a day. */
const STALE_MS = 24 * 60 * 60 * 1000
/** Derived data gets a month before the legacy fixed-name DB is swept. */
const DERIVED_STALE_MS = 30 * 24 * 60 * 60 * 1000
/** common.atomic_write's temp: `.<name>.<8 hex>.tmp` — a dotfile, always. */
const CORE_TEMP = /^\..+\.[0-9a-f]{8}\.tmp$/

/** Instruction dirs once each; the only places deploy.py ever writes backups. */
function instructionDirs(deps: CleanupDeps): string[] {
  return [...new Set(deps.instructionFiles.map((file) => dirname(file)))]
}

function unifiedMemoryDirs(deps: CleanupDeps): string[] {
  return [join(deps.home, '.unified-memory'), join(deps.home, '.unified-memory', 'bin')]
}

/** The vault side, two levels deep: canonical notes, subareas, 已处理/. */
function vaultDirs(deps: CleanupDeps): string[] {
  if (!deps.vaultPath) return []
  const context = join(deps.vaultPath, '50-Agent-Context')
  const dirs = [context]
  let entries: string[]
  try {
    entries = readdirSync(context)
  } catch {
    return dirs
  }
  for (const name of entries) {
    const path = join(context, name)
    try {
      if (statSync(path).isDirectory()) dirs.push(path)
    } catch {
      // Unstatable entry: the top-level dir is still scanned.
    }
  }
  return dirs
}

/**
 * The sweep declarations.
 *
 * Retention: backups keep 3 per file (rollback uses the newest; 3 covers a
 * bad deploy plus its predecessor). Temps are stale after a day. The legacy
 * index DB needs its hashed successor on disk — proof the per-vault layout
 * took over — plus a month of age: derived data, but the one file here a
 * user might conceivably still want to inspect.
 */
export const GARBAGE_RULES: GarbageRule[] = [
  {
    key: 'instruction-backups',
    dirs: instructionDirs,
    match: BACKUP_SUFFIX,
    keepNewest: 3,
  },
  {
    key: 'deploy-temp',
    dirs: (deps) => [...instructionDirs(deps), ...unifiedMemoryDirs(deps)],
    match: /\.tmp-deploy$/,
    olderThanMs: STALE_MS,
  },
  {
    key: 'upgrade-temp',
    dirs: unifiedMemoryDirs,
    match: /\.tmp-upgrade$/,
    olderThanMs: STALE_MS,
  },
  {
    key: 'legacy-index-db',
    dirs: (deps) => [join(deps.home, '.unified-memory')],
    match: /^index\.db$/,
    olderThanMs: DERIVED_STALE_MS,
    requiresSibling: /^index-[0-9a-f]{16}\.db$/,
  },
  {
    // The one rule that reaches into the vault, and only for dotfile temps —
    // see the module comment's second safety rule.
    key: 'core-vault-temp',
    dirs: vaultDirs,
    match: CORE_TEMP,
    olderThanMs: STALE_MS,
  },
]

/**
 * What would be removed, without removing it. Pure with respect to its deps
 * apart from the filesystem reads themselves; the caller decides whether to act.
 */
export function planCleanup(
  deps: CleanupDeps,
  retired: readonly RetiredArtifact[] = RETIRED_PATHS,
  rules: readonly GarbageRule[] = GARBAGE_RULES,
): CleanupTarget[] {
  const targets: CleanupTarget[] = []
  const now = (deps.now?.() ?? new Date()).getTime()

  for (const artifact of retired) {
    for (const path of artifact.paths(deps)) {
      try {
        targets.push({ path, rule: artifact.key, sizeBytes: statSync(path).size })
      } catch {
        // Already gone — the retirement is satisfied.
      }
    }
  }

  for (const rule of rules) {
    for (const dir of rule.dirs(deps)) {
      let names: string[]
      try {
        names = readdirSync(dir)
      } catch {
        continue // Absent dir — nothing of ours was ever there.
      }
      if (rule.requiresSibling && !names.some((name) => rule.requiresSibling?.test(name))) {
        continue // No successor: the old file may still be the live one.
      }
      const matched = names.filter((name) => rule.match.test(name)).map((name) => join(dir, name))
      const stale = (path: string): boolean => {
        if (rule.olderThanMs === undefined) return true
        try {
          return now - statSync(path).mtimeMs >= rule.olderThanMs
        } catch {
          return false
        }
      }
      if (rule.keepNewest !== undefined) {
        // Retention decides by recency alone; an age cutoff is meaningless
        // next to it, so the two options are deliberately exclusive. Same-
        // millisecond writes are real (a deploy loop), and the filename is
        // then the tiebreaker: our generated names embed the stamp, so name-
        // descending is newer-stamp-first.
        const withTime = matched
          .map((path) => {
            try {
              return { path, mtimeMs: statSync(path).mtimeMs }
            } catch {
              return null
            }
          })
          .filter((v): v is { path: string; mtimeMs: number } => v !== null)
          .sort((a, b) => (b.mtimeMs - a.mtimeMs) || b.path.localeCompare(a.path))
        for (const { path } of withTime.slice(rule.keepNewest)) {
          targets.push({ path, rule: rule.key, sizeBytes: 0 })
        }
      } else {
        for (const path of matched) {
          if (!stale(path)) continue
          try {
            targets.push({ path, rule: rule.key, sizeBytes: statSync(path).size })
          } catch {
            // Vanished between readdir and stat — nothing to clean.
          }
        }
      }
    }
  }
  return targets
}

/**
 * Run the sweep. Idempotent: a second run on a swept machine removes nothing.
 * Per-file failures (a lock, a permission) land in `failed` instead of throwing
 * — a locked backup on OneDrive must not turn hygiene into an upgrade failure.
 */
export function runCleanup(
  deps: CleanupDeps,
  retired: readonly RetiredArtifact[] = RETIRED_PATHS,
  rules: readonly GarbageRule[] = GARBAGE_RULES,
): CleanupResult {
  const result: CleanupResult = { removed: [], failed: [], freedBytes: 0 }
  for (const target of planCleanup(deps, retired, rules)) {
    try {
      const size = statSync(target.path).size
      unlinkSync(target.path)
      result.removed.push({ path: target.path, rule: target.rule })
      result.freedBytes += size
    } catch {
      result.failed.push({ path: target.path, rule: target.rule })
    }
  }
  return result
}

/** One line for a log or a test assertion. */
export function summarizeCleanup(result: CleanupResult): string {
  if (result.removed.length === 0 && result.failed.length === 0) return '无可清理。'
  const parts: string[] = []
  if (result.removed.length > 0) parts.push(`清理 ${result.removed.length} 项`)
  if (result.failed.length > 0) parts.push(`${result.failed.length} 项被占用跳过`)
  const kb = Math.round(result.freedBytes / 1024)
  if (kb > 0) parts.push(`约 ${kb} KB`)
  return `${parts.join('，')}。`
}
